const normalize = value => String(value || "").normalize("NFKC").toLocaleLowerCase("en-US").replace(/[’‘]/g,"'").replace(/\s+/g," ").trim();
const escapeRegExp = value => value.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&");

export function distanceKm(lat1, lon1, lat2, lon2) {
  const rad = value => value * Math.PI / 180;
  const dLat = rad(lat2 - lat1), dLon = rad(lon2 - lon1);
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(rad(lat1)) * Math.cos(rad(lat2)) * Math.sin(dLon / 2) ** 2;
  return 6371 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function getNearestDistrict(latitude, longitude, accuracyMeters = 0) {
  const lat = Number(latitude), lon = Number(longitude), accuracy = Number(accuracyMeters) || 0;
  if (!Number.isFinite(lat) || !Number.isFinite(lon) || lat < 20.3 || lat > 26.8 || lon < 87.8 || lon > 93.1 || accuracy > 30000) return null;
  let nearest = null;
  for (const district of DISTRICTS) {
    const km = distanceKm(lat, lon, district.lat, district.lon);
    if (!nearest || km < nearest.distanceKm) nearest = { ...district, distanceKm: Number(km.toFixed(1)) };
  }
  return nearest && nearest.distanceKm <= 100 ? nearest : null;
}

export function getNearbyDistricts(latitude, longitude, localDistrictId, radiusKm = 100, limit = 8) {
  const lat = Number(latitude), lon = Number(longitude);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return [];
  return DISTRICTS.map(district => ({ ...district, distanceKm: Number(distanceKm(lat, lon, district.lat, district.lon).toFixed(1)) }))
    .filter(district => district.id !== String(localDistrictId || "") && district.distanceKm <= radiusKm)
    .sort((a, b) => a.distanceKm - b.distanceKm)
    .slice(0, limit);
}

function matchesPlace(text, place) {
  const term = normalize(place);
  if (!term || term.length < 2) return false;
  if (/[\\u0980-\\u09FF]/.test(term)) return text.includes(term);
  return new RegExp("(^|[^a-z0-9])" + escapeRegExp(term) + "([^a-z0-9]|$)", "i").test(text);
}

function itemText(item) {
  return normalize([item?.title, item?.summary, item?.description, item?.previewTitle, item?.previewSummary, item?.source, item?.publisherName].filter(Boolean).join(" "));
}

function storyTier(item, context) {
  const text = itemText(item);
  const matched = DISTRICTS.filter(district => [district.name, district.bnName, ...district.aliases].some(name => matchesPlace(text, name)));
  const localId = String(context?.district?.id || "");
  if (localId && matched.some(district => district.id === localId)) return 0;
  const nearbyIds = new Set((context?.nearbyDistricts || []).map(district => String(district.id)));
  if (matched.some(district => nearbyIds.has(district.id))) return 1;

  const country = String(context?.country || "").toUpperCase();
  if (country === "BD" || localId) {
    if (matchesPlace(text, context?.city)) return 0;
    if (matchesPlace(text, context?.region)) return 1;
    if (String(item?.category || "").toLowerCase() === "bangladesh") return 2;
    return 3;
  }
  if (matchesPlace(text, context?.city)) return 0;
  if (matchesPlace(text, context?.region)) return 1;
  if (context?.countryName && matchesPlace(text, context.countryName)) return 2;
  return 3;
}

export function rankNewsByLocation(items, context) {
  if (!Array.isArray(items) || !items.length || !context) return items;
  const ranked = items.map((item, index) => ({ item, index, tier: storyTier(item, context) }));
  if (!ranked.some(row => row.tier <= 1)) return items;
  ranked.sort((a, b) => a.tier - b.tier || a.index - b.index);
  return ranked.map(row => row.item);
}

export function buildLocationContext({ latitude, longitude, accuracyMeters = 0, city = "", region = "", country = "", countryName = "" } = {}) {
  const district = getNearestDistrict(latitude, longitude, accuracyMeters);
  const nearbyDistricts = district ? getNearbyDistricts(latitude, longitude, district.id) : [];
  return { district, nearbyDistricts, city: String(city || ""), region: String(region || ""), country: String(country || "").toUpperCase(), countryName: String(countryName || "") };
}

